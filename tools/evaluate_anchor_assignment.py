"""Matched saved-input evaluation of randomized versus deterministic anchors."""
import argparse,hashlib,json
from datetime import datetime,timezone
from pathlib import Path


ROOT=Path(__file__).resolve().parents[1]

def digest(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--comparison',type=Path,help='Multiview comparison.json generated by run_multiview_ablations.py')
    parser.add_argument('--driving-run',type=Path,help='Optional saved drive; compare its first, middle and last captures')
    parser.add_argument('--temporal-captures',type=Path,nargs='+',help='Optional ordered fixed-pose captures for temporal overlap')
    parser.add_argument('--checks-only',action='store_true')
    parser.add_argument('--output',type=Path)
    args=parser.parse_args()
    if not args.checks_only and args.comparison is None:parser.error('--comparison is required unless --checks-only is used')
    if args.comparison and not args.comparison.is_file():parser.error('--comparison does not exist')
    temporal_captures=[p.resolve() for p in (args.temporal_captures or [])]
    if temporal_captures and len(temporal_captures)<2:parser.error('Supply at least two temporal captures')
    cases=[]
    if not args.checks_only:
        previous=json.loads(args.comparison.read_text())
        for pose,sources in previous['sources'].items():
            for appearance in ['simple','reference']:
                source=sources[appearance]
                cases.append((pose+'_'+appearance,Path(source['capture']),Path(source['ground_truth_npz']),source))
        if args.driving_run:
            captures=sorted(p for p in args.driving_run.glob('frame_*') if (p/'capture.json').is_file())
            if not captures:parser.error('--driving-run contains no captures')
            for name,capture in [('drive_start',captures[0]),('drive_midpoint',captures[len(captures)//2]),('drive_end',captures[-1])]:
                cases.append((name,capture,None,None))
    for capture in [c[1] for c in cases]+temporal_captures:
        if not (capture/'capture.json').is_file():parser.error(f'Missing capture: {capture}')
    OUT=(args.output or ROOT/'reports/anchor_assignment_fix'/datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S_%fZ')).resolve()
    OUT.mkdir(parents=True,exist_ok=False)
    import numpy as np
    import torch,cv2
    from prepare_capture import prepare
    from run_gaussianformer3d import build_model,build_queries,infer_arrays
    from occupancy_evaluation import confusion,metrics
    from test_anchor_assignment import check_assignment
    torch.set_num_threads(4);torch.set_num_interop_threads(1);cv2.setNumThreads(1)
    torch.manual_seed(42);np.random.seed(42)
    model,config,tensors=build_model();queries=build_queries(config)
    checks=check_assignment(model)
    if args.checks_only:
        (OUT/'assignment-checks.json').write_text(json.dumps(checks,indent=2))
        print(json.dumps(checks),flush=True)
        return
    result={'method':'No threshold or seed tuning. Ten distinct paired seeds plus a repeat of seed 42; alternating execution order.',
            'strict_tensor_count':tensors,'checkpoint_sha256':digest(ROOT/'checkpoints/surroundocc_release.pth'),
            'helper_sha256':digest(ROOT/'GaussianFormer3D/model/lifter/anchor_assignment.py'),
            'checks':checks,'comparison':str(args.comparison.resolve()),'anchor_policies':['random','deterministic'],'sources':{},'runs':[],'temporal_runs':[]}
    xyz=(np.indices((200,200,16)).reshape(3,-1).T+.5)*.5+[-50.,-50.,-5.]
    for name,capture,truthpath,source in cases:
        arrays=prepare(capture);metadata=json.loads((capture/'capture.json').read_text())
        if source:
            assert digest(capture/'capture.json')==source['capture_sha256']
            assert digest(capture/metadata['lidar']['points'])==source['lidar_sha256']
            for camera in metadata['cameras']:
                assert digest(capture/camera['image'])==source['rgb_sha256'][camera['name']]
        transform=np.asarray(metadata['world_from_ego'])@np.asarray(metadata['lidar']['ego_from_lidar'])
        z=(xyz@transform[:3,:3].T+transform[:3,3])[:,2].reshape(200,200,16)
        truth=np.load(truthpath) if truthpath else None
        mask=truth['obstacles_above_ground'] if truth is not None else np.ones((200,200,16),bool)
        result['sources'][name]={'capture':str(capture),'capture_sha256':digest(capture/'capture.json'),
            'ground_truth':str(truthpath) if truthpath else None,'ground_truth_sha256':digest(truthpath) if truthpath else None}
        counts=[]
        def count_hook(module,args,kwargs):counts.append(len(kwargs['coors_batch']))
        handle=model.lifter.register_forward_pre_hook(count_hook,with_kwargs=True)
        references={}
        for mode in ['random','deterministic']:
            model.lifter.deterministic_eval=mode=='deterministic'
            infer_arrays(model,config,arrays,queries)
        for repeat,seed in enumerate([*range(42,52),42]):
            order=['random','deterministic'] if repeat%2==0 else ['deterministic','random']
            for mode in order:
                model.lifter.deterministic_eval=mode=='deterministic'
                torch.manual_seed(seed);np.random.seed(seed);counts.clear()
                raw,confidence,timing=infer_arrays(model,config,arrays,queries)
                display=(raw>0)&~np.isin(raw,[11,12,13,14,17])&(confidence>=.35)&(z>.3)&(z<2.5)
                if mode not in references:
                    references[mode]=(raw.copy(),display.copy())
                    np.savez_compressed(OUT/(name+'-'+mode+'.npz'),raw=raw,confidence=confidence)
                reference,refdisplay=references[mode];union=(display|refdisplay)&mask
                overlap=float(np.count_nonzero(display&refdisplay&mask)/union.sum()) if union.any() else 1.
                row={'case':name,'mode':mode,'repeat':repeat,'seed':seed,'lifter_voxels':counts[-1],
                     'overlay_jaccard':overlap,'label_agreement':float((raw[mask]==reference[mask]).mean()),**timing}
                if truth is not None:
                    row['raw_score']=metrics(confusion(raw!=17,truth['occupied'],mask))
                    row['display_score']=metrics(confusion(display,truth['occupied'],mask))
                result['runs'].append(row)
            (OUT/'results.json').write_text(json.dumps(result,indent=2))
        handle.remove()
        print('CASE_COMPLETE',name,flush=True)
    # Real consecutive captures of the stopped car, allowing sensor jitter.
    for mode in ['random','deterministic']:
        model.lifter.deterministic_eval=mode=='deterministic';reference=None
        for index,capture in enumerate(temporal_captures):
            arrays=prepare(capture)
            meta=json.loads((capture/'capture.json').read_text());tf=np.asarray(meta['world_from_ego'])@np.asarray(meta['lidar']['ego_from_lidar'])
            if reference is None:ref_transform=tf.copy()
            assert np.allclose(ref_transform,tf,atol=1e-4,rtol=0),'Temporal overlap requires a fixed sensor pose'
            z=(xyz@tf[:3,:3].T+tf[:3,3])[:,2].reshape(200,200,16)
            torch.manual_seed(100+index);np.random.seed(100+index)
            raw,conf,timing=infer_arrays(model,config,arrays,queries)
            display=(raw>0)&~np.isin(raw,[11,12,13,14,17])&(conf>=.35)&(z>.3)&(z<2.5)
            overlap=None if reference is None else float((display&reference).sum()/(display|reference).sum())
            result['temporal_runs'].append({'mode':mode,'frame':index,'overlay_jaccard_to_previous':overlap,**timing})
            reference=display
    model.lifter.deterministic_eval=True
    (OUT/'results.json').write_text(json.dumps(result,indent=2))
    print('ANCHOR_EVALUATION_COMPLETE',flush=True)

if __name__=='__main__':main()
